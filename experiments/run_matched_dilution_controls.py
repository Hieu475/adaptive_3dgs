#!/usr/bin/env python3
"""Run matched dilution controls E1-E5.

Pilot targets are read from the existing corrected-pose factorial artifacts.
Pairs are marked valid only when the realized map/spawn counts meet the target.
"""
import argparse
import json
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from experiments.run_dilution_factorial import config_for
from experiments.run_frozen_benchmark import load_benchmark_sequence, run_policy_trajectory
from src.evaluation.reproducibility import create_provenance_manifest


def run_arm(scene, seed, condition, cfg, frames, intrinsics, args,
            final_gaussian_target=None):
    pose_convention = (
        "W2C extrinsics.npy generated by inverting Replica traj.txt C2W in scripts/download_replica_scene.py; passed directly to pipeline"
        if scene.startswith("replica_") else
        "W2C via inverse TUM C2W groundtruth"
    )
    summary, logs = run_policy_trajectory(
        policy="error_only", seed=seed, frames=frames, intrinsics=intrinsics,
        budget_ms=args.budget_ms, device=args.device, W=320, H=240,
        custom_config=cfg, final_gaussian_target=final_gaussian_target,
    )
    return {"scene": scene, "seed": seed, "condition": condition,
            "manifest": create_provenance_manifest(
                config=cfg, dataset_name=scene,
                renderer_backend="gsplat" if args.device.startswith("cuda") else "reference",
                extra_metadata={"experiment": "matched_dilution_controls",
                                "condition": condition, "seed": seed,
                                "pose_convention": pose_convention,
                                "status": "exploratory"}),
            "config": cfg, "summary": summary, "frames": logs}


def save_pair(out_path, record):
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_suffix(".tmp")
    tmp.write_text(json.dumps(record, indent=2))
    tmp.replace(out_path)
    print(f"{out_path.name}: valid={record['valid']} {record['validation']}", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenes", nargs="+", default=["tum_fr2_xyz", "tum_fr1_xyz"])
    ap.add_argument("--seeds", type=int, nargs="+", default=list(range(42, 50)))
    ap.add_argument("--n_frames", type=int, default=150)
    ap.add_argument("--budget_ms", type=float, default=15.0)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--out_dir", type=Path, default=ROOT / "results" / "matched_dilution_controls")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--controls", nargs="+", choices=("e1", "e2", "e3", "e5"), default=["e1", "e2"])
    ap.add_argument("--e3_micro_updates_per_frame", type=int, default=50000,
                    help="Exact Gaussian-micro-update quota for both E3 arms")
    ap.add_argument("--e5_micro_updates_per_frame", type=int, default=50000,
                    help="Exact Gaussian-micro-update quota for E5 age-allocation arms")
    ap.add_argument("--e2_target_spawns", type=int, default=None,
                    help="Optional frozen total spawn count shared across E2 seeds/scenes")
    ap.add_argument("--e2_candidate_mode", choices=("uniform_depth", "error_first"),
                    default="uniform_depth",
                    help="E2 proposal pool; error_first samples the error mask then fills shortfall from valid depth")
    args = ap.parse_args()
    args.out_dir = args.out_dir if args.out_dir.is_absolute() else ROOT / args.out_dir
    if args.device.startswith("cuda"):
        torch.cuda.set_per_process_memory_fraction(0.70, 0)

    study_manifest = create_provenance_manifest(
        config={"scenes": args.scenes, "seeds": args.seeds, "frames": args.n_frames,
                "budget_ms": args.budget_ms,
                "E1": "post-trajectory final-size match by lowest-opacity pruning; final-frame re-render",
                "E2": {"design": "matched total spawn count; early vs late windows",
                       "candidate_mode": args.e2_candidate_mode,
                       "frozen_target_spawns": args.e2_target_spawns},
                "E3": {"micro_updates_per_frame": args.e3_micro_updates_per_frame,
                       "selection": "descending importance stable sort",
                       "status": "exact per-frame Gaussian-microstep count; hardware work may differ"},
                "E4": "replay fixed validation/cross-scene-test oracle candidate pools; matched top-20% quota; singleton utility ranking diagnostics",
                "E5": {"micro_updates_per_frame": args.e5_micro_updates_per_frame,
                       "mature_age_frames": 10, "mature_update_fractions": [0.25, 0.50, 0.75],
                       "control": "unconstrained importance allocation from E3 no-throttle arm"}},
        dataset_name=",".join(args.scenes),
        renderer_backend="gsplat" if args.device.startswith("cuda") else "reference",
        extra_metadata={"experiment": "matched_dilution_controls", "status": "exploratory",
                        "pose_convention_by_scene": {
                            scene: ("W2C extrinsics.npy generated by inverting Replica traj.txt C2W in scripts/download_replica_scene.py; passed directly to pipeline"
                                    if scene.startswith("replica_") else
                                    "W2C via inverse TUM C2W groundtruth")
                            for scene in args.scenes
                        },
                        "seed_list": args.seeds},
    )
    manifest_path = args.out_dir / "manifest.json"
    args.out_dir.mkdir(parents=True, exist_ok=True)
    if not manifest_path.exists() or args.force:
        manifest_path.write_text(json.dumps(study_manifest, indent=2))

    for scene in args.scenes:
        frames, intrinsics = load_benchmark_sequence(scene_name=scene,
            n_frames=args.n_frames + 1, H=240, W=320, device=args.device)
        n_online_frames = min(args.n_frames, max(0, len(frames) - 1))
        print(f"{scene}: {len(frames)} source frames, {n_online_frames} online frames; "
              f"E2 windows will use the realized trajectory length.", flush=True)
        for seed in args.seeds:

            # E1: run natural policies, choose a shared final size, then prune
            # both final maps by the same opacity rule and re-evaluate the last
            # frame. The treatment does not alter the online trajectories.
            e1_path = args.out_dir / scene / f"E1_seed{seed}.json"
            if "e1" in args.controls and (not e1_path.exists() or args.force):
                pilots = []
                for name, throttle in (("no_throttle_size_pilot", False),
                                       ("coverage_size_pilot", True)):
                    _, pilot_cfg = config_for("error_coverage" if throttle else "error_off",
                                              seed, args.budget_ms, args.device)
                    pilots.append(run_arm(scene, seed, name, pilot_cfg,
                                          frames, intrinsics, args))
                pilot_min = min(int(p["summary"]["N_final_active"]) for p in pilots)
                n_init = min(int(p["summary"]["N_init"]) for p in pilots)
                # Leave headroom for run-to-run CUDA variability so both
                # natural trajectories can reach the common post-hoc target.
                target_size = max(n_init + 1, pilot_min - 5000)
                arms = []
                for name, throttle in (("no_throttle_matched_final", False),
                                       ("coverage_throttle_matched_final", True)):
                    _, cfg = config_for("error_coverage" if throttle else "error_off",
                                        seed, args.budget_ms, args.device)
                    arms.append(run_arm(scene, seed, name, cfg, frames, intrinsics, args,
                                        final_gaussian_target=target_size))
                counts = [int(a["summary"]["matched_final_map"]["n_gaussians"]) for a in arms]
                valid = (counts == [target_size, target_size]
                         and all(a["summary"]["matched_final_map"]["valid"] for a in arms))
                save_pair(e1_path, {"experiment": "E1_matched_final_map_size",
                    "scene": scene, "seed": seed, "target_final_gaussians": target_size,
                    "valid": valid, "validation": {"final_counts": counts,
                    "exact_target_reached_by_both": valid},
                    "size_pilots": pilots, "arms": arms})

            # E2: equal total additions with births concentrated in disjoint
            # trajectory windows. Missed quota in either run invalidates pair.
            e2_path = args.out_dir / scene / f"E2_seed{seed}.json"
            if "e2" in args.controls and (not e2_path.exists() or args.force):
                arms = []
                _, natural_cfg = config_for("error_off", seed, args.budget_ms, args.device)
                natural_pilot = run_arm(scene, seed, "unthrottled_spawn_pilot",
                                        natural_cfg, frames, intrinsics, args)
                pilot_spawn_total = int(sum(f["n_spawned"] for f in natural_pilot["frames"]))
                target_spawns = (int(args.e2_target_spawns) if args.e2_target_spawns is not None
                                 else pilot_spawn_total)
                if target_spawns < 0:
                    raise ValueError("--e2_target_spawns must be nonnegative")
                # A natural trajectory can accumulate more births than fit
                # below the canonical map cap because pruning frees capacity.
                # Give both timing arms the same cap large enough for the
                # exact target, so capacity cannot selectively invalidate an
                # arm or turn the timing contrast into a cap-pressure test.
                _, capacity_cfg = config_for("error_off", seed, args.budget_ms, args.device)
                e2_max_gaussians = int(capacity_cfg["gaussian"]["max_gaussians"])
                e2_max_gaussians = max(e2_max_gaussians,
                                       int(natural_pilot["summary"]["N_init"]) + target_spawns)
                midpoint = max(1, n_online_frames // 2)
                windows = (("early_spawn", 1, midpoint),
                           ("late_spawn", midpoint + 1, n_online_frames))
                for name, start, end in windows:
                    _, cfg = config_for("error_off", seed, args.budget_ms, args.device)
                    cfg["gaussian"]["max_gaussians"] = max(
                        int(cfg["gaussian"]["max_gaussians"]), e2_max_gaussians
                    )
                    cfg["densification"]["spawn_control"] = {
                        "target_total": target_spawns,
                        "start_frame": start,
                        "end_frame": end,
                        "candidate_mode": args.e2_candidate_mode,
                    }
                    arms.append(run_arm(scene, seed, name, cfg, frames, intrinsics, args))
                realized = [int(sum(f["n_spawned"] for f in a["frames"])) for a in arms]
                valid = realized == [target_spawns, target_spawns]
                save_pair(e2_path, {"experiment": "E2_matched_spawn_count_timing",
                    "scene": scene, "seed": seed, "target_total_spawned": target_spawns,
                    "pilot_total_spawned": pilot_spawn_total,
                    "target_selection": ("frozen_cli_target" if args.e2_target_spawns is not None
                                         else "per_seed_natural_pilot"),
                    "shared_gaussian_capacity": e2_max_gaussians,
                    "valid": valid, "validation": {"realized_total_spawned": realized,
                    "exact_target_reached_by_both": valid,
                    "fallback_spawned": [int(sum(f.get("n_spawned_fallback", 0)
                                                 for f in a["frames"])) for a in arms],
                    "early_window": [1, midpoint],
                    "late_window": [midpoint + 1, n_online_frames],
                    "realized_online_frames": n_online_frames,
                    "candidate_mode": args.e2_candidate_mode},
                    "unthrottled_spawn_pilot": natural_pilot, "arms": arms})

            # E3: both policies receive the same exact optimizer micro-update
            # count on every frame. Importance still determines which
            # primitives receive those updates; measured time is reported as
            # an outcome because cache/render overhead can differ.
            e3_path = args.out_dir / scene / f"E3_seed{seed}.json"
            if "e3" in args.controls and (not e3_path.exists() or args.force):
                arms = []
                for name, policy_name in (("no_throttle", "error_off"),
                                          ("coverage_throttle", "error_coverage")):
                    _, cfg = config_for(policy_name, seed, args.budget_ms, args.device)
                    cfg["system"]["synchronized_stage_timing"] = True
                    cfg["training"]["optimization_control"] = {
                        "micro_updates_per_frame": args.e3_micro_updates_per_frame,
                        "selection": "descending_importance_stable",
                    }
                    arms.append(run_arm(scene, seed, f"E3_{name}", cfg,
                                        frames, intrinsics, args))
                realized = [[int(f.get("n_micro_updates", -1)) for f in a["frames"]]
                            for a in arms]
                valid = all(all(v == args.e3_micro_updates_per_frame for v in seq)
                            for seq in realized)
                save_pair(e3_path, {"experiment": "E3_matched_optimizer_micro_updates",
                    "scene": scene, "seed": seed,
                    "target_micro_updates_per_frame": args.e3_micro_updates_per_frame,
                    "valid": valid,
                    "validation": {"all_frames_exact_match": valid,
                                   "realized_min_max": [[min(x), max(x)] for x in realized]},
                    "arms": arms})

            # E5: fixed total optimizer work, redistributed across young and
            # mature visible Gaussians. The no-throttle unconstrained arm from
            # E3 is the shared reference, so it is not recomputed here.
            e5_path = args.out_dir / scene / f"E5_seed{seed}.json"
            if "e5" in args.controls and (not e5_path.exists() or args.force):
                arms = []
                fractions = (0.25, 0.50, 0.75)
                for fraction in fractions:
                    _, cfg = config_for("error_off", seed, args.budget_ms, args.device)
                    cfg["system"]["synchronized_stage_timing"] = True
                    cfg["training"]["optimization_control"] = {
                        "micro_updates_per_frame": args.e5_micro_updates_per_frame,
                        "selection": "descending importance within age group",
                        "mature_age_frames": 10,
                        "mature_update_fraction": fraction,
                    }
                    arms.append(run_arm(scene, seed, f"E5_mature_{int(fraction*100)}pct",
                                        cfg, frames, intrinsics, args))
                exact_counts = [[int(f.get("n_micro_updates", -1)) for f in a["frames"]]
                                for a in arms]
                valid = all(all(v == args.e5_micro_updates_per_frame for v in seq)
                            for seq in exact_counts)
                save_pair(e5_path, {"experiment": "E5_matched_work_age_quota",
                    "scene": scene, "seed": seed,
                    "target_micro_updates_per_frame": args.e5_micro_updates_per_frame,
                    "mature_age_frames": 10,
                    "requested_mature_update_fractions": list(fractions),
                    "valid": valid,
                    "validation": {"all_frames_exact_match": valid,
                        "realized_min_max": [[min(x), max(x)] for x in exact_counts]},
                    "arms": arms})


if __name__ == "__main__":
    main()
